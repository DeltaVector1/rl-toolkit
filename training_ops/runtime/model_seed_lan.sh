#!/usr/bin/env bash
set -euo pipefail

# The model path and LAN values are fixed for this seed service. The two path
# overrides make the checks safe to exercise with a disposable fixture.
model_dir=${MODEL_SEED_MODEL_DIR:-/data/trinity-thinking-fp8}
state_dir=${MODEL_SEED_STATE_DIR:-/tmp/model-seed-lan}
source_ip=10.92.20.82
source_port=18229
expected_shards=81
expected_files=96
manifest_name=manifest.sha256
config_name=rsyncd.conf
pid_name=rsyncd.pid
log_name=rsyncd.log
partial_dir=${MODEL_SEED_PARTIAL_DIR:-/data/.trinity-thinking-fp8.partial}

config_file=$state_dir/$config_name
manifest_file=$state_dir/$manifest_name
pid_file=$state_dir/$pid_name
log_file=$state_dir/$log_name

target_hosts=(
  10.92.20.76
  10.92.20.77
  10.92.20.78
  10.92.20.80
  10.92.20.83
  10.92.20.84
  10.92.20.85
)

die() {
  echo "model seed: $*" >&2
  exit 1
}

usage() {
  echo "usage: $0 {source-start|target-pull|verify|source-stop}" >&2
  exit 2
}

require_tools() {
  local tool
  for tool in find sha256sum rsync; do
    command -v "$tool" >/dev/null 2>&1 || die "$tool is not installed"
  done
}

check_incomplete_names() {
  local path name lower
  while IFS= read -r -d '' path; do
    name=${path##*/}
    lower=${name,,}
    case "$lower" in
      *.part|*.partial|*.incomplete|*.tmp|*.temp|*.download|*.crdownload|*.range|model-*.safetensors_*|*incomplete*|*range*)
        die "source contains an incomplete or range file: $name"
        ;;
    esac
  done < <(find "$model_dir" -maxdepth 1 -type f -print0)
}

check_source() {
  local i expected path name shard_count=0 top_level_files=0
  [ -d "$model_dir" ] || die "model directory is missing: $model_dir"
  check_incomplete_names

  while IFS= read -r -d '' path; do
    top_level_files=$((top_level_files + 1))
  done < <(find "$model_dir" -maxdepth 1 -type f -print0)
  [ "$top_level_files" -eq "$expected_files" ] || {
    die "expected $expected_files top-level model files, found $top_level_files"
  }

  # Reject a partial or differently-sized shard set. This also rejects extra
  # model-*-of-* files, not only a missing member of the expected set.
  while IFS= read -r -d '' path; do
    name=${path##*/}
    case "$name" in
      model-*-of-*.safetensors)
        shard_count=$((shard_count + 1))
        ;;
    esac
  done < <(find "$model_dir" -maxdepth 1 -type f -print0)
  [ "$shard_count" -eq "$expected_shards" ] || {
    die "expected $expected_shards model shards, found $shard_count"
  }

  for ((i = 1; i <= expected_shards; i++)); do
    expected=$(printf 'model-%05d-of-%05d.safetensors' "$i" "$expected_shards")
    path=$model_dir/$expected
    [ -f "$path" ] || die "missing model shard: $expected"
  done
}

check_state_is_empty_or_missing() {
  if [ -e "$state_dir" ]; then
    [ -d "$state_dir" ] || die "state path is not a directory: $state_dir"
    [ -z "$(find "$state_dir" -mindepth 1 -maxdepth 1 -print -quit)" ] || {
      die "state directory is not empty: $state_dir"
    }
  else
    mkdir -p -- "$state_dir"
  fi
}

write_manifest() {
  local path temp
  temp=$state_dir/.manifest.sha256.tmp.$$
  (
    cd -- "$model_dir"
    while IFS= read -r -d '' path; do
      sha256sum -- "$path"
    done < <(find . -maxdepth 1 -type f -print0 | LC_ALL=C sort -z)
  ) >"$temp"
  mv -f -- "$temp" "$manifest_file"
  chmod 0444 "$manifest_file"
}

write_config() {
  local allow_hosts host
  allow_hosts=${target_hosts[0]}
  for host in "${target_hosts[@]:1}"; do
    allow_hosts+=", $host"
  done
  umask 077
  cat >"$config_file" <<EOF
# Generated by model_seed_lan.sh. This file is read-only after creation.
port = $source_port
address = $source_ip
use chroot = no
read only = yes
max connections = 16

[model]
path = $model_dir
read only = yes
hosts allow = $allow_hosts
hosts deny = *
exclude = /*/

[manifest]
path = $state_dir
read only = yes
hosts allow = $allow_hosts
hosts deny = *
include = /$manifest_name
exclude = *
EOF
  chmod 0444 "$config_file"
}

pid_is_ours() {
  local pid=$1 command_line
  [ "$pid" -gt 1 ] 2>/dev/null || return 1
  [ -r "/proc/$pid/cmdline" ] || return 1
  command_line=$(tr '\0' ' ' <"/proc/$pid/cmdline") || return 1
  case "$command_line" in
    *rsync*--daemon*--no-detach*--config*"$config_file"*) return 0 ;;
    *) return 1 ;;
  esac
}

cleanup_start_failure() {
  local pid=${1:-}
  if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null && pid_is_ours "$pid"; then
    kill "$pid" 2>/dev/null || true
  fi
  rm -f -- "$config_file" "$manifest_file" "$pid_file" "$log_file"
  rmdir -- "$state_dir" 2>/dev/null || true
}

source_start() {
  local pid
  require_tools
  check_source
  check_state_is_empty_or_missing
  write_manifest
  write_config

  # --no-detach keeps the recorded PID equal to the daemon process, rather
  # than a short-lived launcher or a detached parent.
  rsync --daemon --no-detach --config "$config_file" >"$log_file" 2>&1 &
  pid=$!
  printf '%s\n' "$pid" >"$pid_file"
  chmod 0444 "$pid_file"
  if ! pid_is_ours "$pid"; then
    cleanup_start_failure "$pid"
    die "rsync daemon did not start with the expected identity"
  fi
  echo "model seed source started: pid=$pid address=$source_ip port=$source_port"
}

read_recorded_pid() {
  local pid
  [ -r "$pid_file" ] || die "recorded daemon PID is missing: $pid_file"
  pid=$(sed -n '1p' "$pid_file")
  case "$pid" in
    ''|*[!0-9]*) die "recorded daemon PID is invalid: $pid" ;;
  esac
  printf '%s\n' "$pid"
}

verify_manifest() {
  local check_manifest=$1
  [ -f "$check_manifest" ] || die "manifest is missing: $check_manifest"
  [ -d "$model_dir" ] || die "model directory is missing: $model_dir"
  (
    cd -- "$model_dir"
    sha256sum --check -- "$check_manifest"
  )
}

target_pull() {
  local target_manifest path
  require_tools
  mkdir -p -- "$state_dir"
  mkdir -p -- "$model_dir"
  mkdir -p -- "$partial_dir"
  target_manifest=$state_dir/$manifest_name
  rsync -a --checksum --partial --append-verify \
    --partial-dir="$partial_dir" --protect-args --timeout=600 --contimeout=30 \
    "rsync://$source_ip:$source_port/model/" "$model_dir/"
  rsync -a --checksum --partial --append-verify \
    --protect-args --timeout=600 --contimeout=30 \
    "rsync://$source_ip:$source_port/manifest/$manifest_name" "$target_manifest"
  verify_manifest "$target_manifest"
  while IFS= read -r -d '' path; do
    rm -f -- "$path"
  done < <(find "$model_dir" -maxdepth 1 -type f -name 'model-*.safetensors_*' -print0)
  if [ -d "$partial_dir" ] && [ ! -L "$partial_dir" ]; then
    rm -rf -- "$partial_dir"
  fi
  echo "model seed pull verified: $model_dir"
}

verify() {
  require_tools
  verify_manifest "$manifest_file"
}

source_stop() {
  local pid
  pid=$(read_recorded_pid)
  if kill -0 "$pid" 2>/dev/null; then
    pid_is_ours "$pid" || die "recorded PID is not this model seed daemon: $pid"
    kill "$pid"
    for _ in {1..50}; do
      kill -0 "$pid" 2>/dev/null || break
      sleep 0.1
    done
    if kill -0 "$pid" 2>/dev/null; then
      pid_is_ours "$pid" || die "daemon identity changed while stopping: $pid"
      kill -KILL "$pid"
    fi
  fi

  # Remove only files created by this script. Keep the state directory if it
  # contains anything unrelated to this service.
  rm -f -- "$config_file" "$manifest_file" "$pid_file" "$log_file"
  rmdir -- "$state_dir" 2>/dev/null || true
  echo "model seed source stopped: pid=$pid"
}

command=${1:-}
case "$command" in
  source-start)
    [ "$#" -eq 1 ] || usage
    source_start
    ;;
  target-pull)
    [ "$#" -eq 1 ] || usage
    target_pull
    ;;
  verify)
    [ "$#" -eq 1 ] || usage
    verify
    ;;
  source-stop)
    [ "$#" -eq 1 ] || usage
    source_stop
    ;;
  *)
    usage
    ;;
esac
